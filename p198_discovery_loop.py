"""P198: DISCOVERY LOOP v0 — first integrated run of the L4 parts.
Open edge: do the new 2-elementary rows have quadratic landing fields?
Known: d=4 -> Q(sqrt 3), d=8 -> Q(sqrt 6); hidden: the other 9 rows (truth:
ALL FULL genus real part — no quadratic landing).
Loop per round: PROPOSE(rule + per-row predictions) -> VERIFY(exact truth
table) -> ERROR(feedback) -> UPDATE(revise). Cost: calls logged. Models x 3
rounds. This is an integration test: how far does the loop get autonomously,
and where does it stall?
"""
import os, sys, json, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
MODELS = ["deepseek-v4-flash", "doubao-seed-2.1-lite"]
ALL_D = [4, 8, 12, 20, 28, 40, 52, 68, 140, 220, 308]
TRUTH = {4: 3, 8: 6}   # others: FULL

GENS = {4: [2, 3], 8: [2, 3], 12: [2, 3], 20: [2, 3, 5], 28: [2, 3, 7],
        40: [2, 3, 5], 52: [2, 3, 13], 68: [2, 3, 17],
        140: [2, 3, 5, 7], 220: [2, 3, 5, 11], 308: [2, 3, 7, 11]}

def parse_predictions(ans):
    out = {}
    for line in ans.splitlines():
        m = re.search(r"d\s*=\s*(\d+)\s*[:\-]\s*(FULL|LANDING\s*s\s*=\s*(\d+))", line, re.I)
        if m:
            d = int(m.group(1))
            out[d] = "FULL" if m.group(2).upper().startswith("FULL") else int(m.group(3))
    return out

def score(preds):
    errs = []
    for d in ALL_D:
        t = TRUTH.get(d, "FULL")
        p = preds.get(d, "MISSING")
        if p != t:
            errs.append({"d": d, "truth": t, "pred": p})
    return errs

def main():
    import importlib, llm_client
    out = {}
    for model in MODELS:
        os.environ["ARK_MODEL"] = model
        importlib.reload(llm_client)
        rounds = []
        history = ""
        for rnd in range(1, 4):
            seed_rows = "\n".join(
                f"  d={d} (genus generators {GENS[d]}): landing field Q(sqrt({TRUTH[d]}))"
                for d in sorted(TRUTH))
            if history:
                task = (f"Your previous rule failed on some rows:\n{history}\n"
                        "Revise the rule and give a COMPLETE prediction table for ALL rows below.\n")
            else:
                task = ""
            prompt = (
                "BACKGROUND: For special denominators d, the quantity P^12(tau0) lands "
                "in a quadratic field Q(sqrt(s)). Known rule for the six prime rows: "
                "s = c*d with c in {1,2,3} determined by d mod 3 and d mod 4.\n\n"
                "NEW FAMILY: d = 4*d' rows (4x-shadows of a 2-elementary census). "
                "Each row has a genus real part generated by square roots of the "
                "listed generators. Two rows are solved:\n" + seed_rows +
                f"\n\nThe remaining rows: "
                + ", ".join(f"d={d} (generators {GENS[d]})" for d in ALL_D if d not in TRUTH) +
                "\n\nTASK 1: State a rule predicting which of these rows have a QUADRATIC "
                "landing field (and its s) versus which span the FULL genus real part.\n"
                "TASK 2: Give a prediction line for EVERY row, format exactly:\n"
                "d=<d>: LANDING s=<s>   or   d=<d>: FULL\n"
                + task +
                "Format:\nRULE: <sentence>\nPREDICTIONS:\n<lines>")
            ans = llm_client.ask(prompt)
            m = re.search(r"RULE:\s*(.+?)(?=\nPREDICTIONS:|\Z)", ans, re.S)
            rule = m.group(1).strip()[:500] if m else "(none)"
            preds = parse_predictions(ans)
            errs = score(preds)
            rounds.append({"round": rnd, "rule": rule, "preds": {str(k): str(v) for k, v in preds.items()},
                           "n_errs": len(errs), "errs": errs, "raw": ans[-500:]})
            print(f"{model} round{rnd}: rule_len={len(rule)} errs={len(errs)} "
                  f"{[(e['d'], e['truth'], e['pred']) for e in errs][:5]}")
            history = "\n".join(f"  d={e['d']}: truth={'FULL' if e['truth']=='FULL' else 'Q(sqrt '+str(e['truth'])+')'}, "
                                f"you predicted {e['pred']}" for e in errs[:8])
            if not errs:
                break
        calls = len(rounds)
        out[model] = {"rounds": rounds, "calls_used": calls,
                      "solved": rounds[-1]["n_errs"] == 0}
    json.dump(out, open("p198_discovery_loop.json", "w"), indent=1)
    print("saved p198_discovery_loop.json")

if __name__ == "__main__":
    main()
